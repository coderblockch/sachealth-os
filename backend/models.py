"""SQLModel tables for SacHealth OS.

Schema overview (see README "Data model"):

    user ──< triage_record >── patient ──< bed (current occupant)

Changes to these classes must be accompanied by an Alembic migration
(``alembic revision --autogenerate -m "..."``).
"""

from datetime import datetime, timezone
from typing import Optional

from sqlalchemy import CheckConstraint, Column, DateTime, ForeignKey, Index, Integer
from sqlmodel import Field, SQLModel

BED_STATUSES = ("Available", "Occupied", "Pending_Discharge", "Cleaning")
URGENCY_LEVELS = ("CRITICAL", "High", "Moderate", "Low")


# Deterministic constraint names so Alembic migrations can reference them
# (check constraints are named explicitly in each table).
SQLModel.metadata.naming_convention = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


def _timestamp_column(**kwargs) -> Column:
    return Column(DateTime(timezone=True), nullable=False, default=utcnow, **kwargs)


class Patient(SQLModel, table=True):
    """A person who has been triaged. Kept minimal on purpose (demo data only)."""

    __table_args__ = (
        CheckConstraint("age >= 0 AND age <= 130", name="ck_patient_age_range"),
    )

    id: Optional[int] = Field(default=None, primary_key=True)
    full_name: str = Field(max_length=120, index=True)
    age: int
    created_at: datetime = Field(default_factory=utcnow, sa_column=_timestamp_column())


class Bed(SQLModel, table=True):
    """A hospital bed. ``patient`` is the display name shown on the dashboard;
    ``patient_id`` links to a registered patient when the bed was assigned
    through ``POST /beds/{id}/assign``."""

    __table_args__ = (
        CheckConstraint(
            "status IN ('Available', 'Occupied', 'Pending_Discharge', 'Cleaning')",
            name="ck_bed_status",
        ),
    )

    # Primary key: auto-generated by the database (1, 2, 3...)
    id: Optional[int] = Field(default=None, primary_key=True)

    # Bed number (e.g. "101"); unique across the hospital
    num: str = Field(max_length=20, unique=True, index=True)

    # Occupied, Available, Pending_Discharge or Cleaning
    status: str = Field(max_length=20, index=True)

    # Patient name. Optional because an empty bed has no patient.
    patient: Optional[str] = Field(default=None, max_length=120)

    # Registered patient currently in the bed (NULL when free or set by name only)
    patient_id: Optional[int] = Field(
        default=None,
        sa_column=Column(
            Integer,
            ForeignKey("patient.id", ondelete="SET NULL"),
            nullable=True,
            unique=True,  # a patient can occupy at most one bed
        ),
    )

    updated_at: datetime = Field(
        default_factory=utcnow, sa_column=_timestamp_column(onupdate=utcnow)
    )


class User(SQLModel, table=True):
    # Clinical staff account. Passwords are stored only as bcrypt hashes.
    id: Optional[int] = Field(default=None, primary_key=True)
    email: str = Field(index=True, unique=True, max_length=254)
    full_name: str = Field(default="", max_length=120)
    hashed_password: str = Field(max_length=255)


class TriageRecord(SQLModel, table=True):
    """One CDSS evaluation, stored for the patient's triage history."""

    __tablename__ = "triage_record"
    __table_args__ = (
        CheckConstraint("priority BETWEEN 1 AND 4", name="ck_triage_priority_range"),
        CheckConstraint(
            "oxygen_level >= 0 AND oxygen_level <= 100", name="ck_triage_oxygen_range"
        ),
        CheckConstraint("age >= 0 AND age <= 130", name="ck_triage_age_range"),
        # Typical query: a patient's history, newest first
        Index("ix_triage_record_patient_created", "patient_id", "created_at"),
        # Typical query: the queue of critical patients, newest first
        Index("ix_triage_record_priority_created", "priority", "created_at"),
    )

    id: Optional[int] = Field(default=None, primary_key=True)
    patient_id: int = Field(
        sa_column=Column(
            Integer, ForeignKey("patient.id", ondelete="CASCADE"), nullable=False
        )
    )
    age: int
    oxygen_level: int
    symptoms: str = Field(default="", max_length=2000)
    priority: int
    recommendation: str = Field(max_length=80)
    urgency: str = Field(max_length=20)
    created_by_id: Optional[int] = Field(
        default=None,
        sa_column=Column(Integer, ForeignKey("user.id", ondelete="SET NULL"), nullable=True),
    )
    created_at: datetime = Field(default_factory=utcnow, sa_column=_timestamp_column())
